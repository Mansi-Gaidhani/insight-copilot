import operator
from typing import Annotated, TypedDict, Union, List, Dict, Any
from langchain_core.messages import BaseMessage, HumanMessage, AIMessage
from langgraph.graph import StateGraph, END

# 1. Define the Graph State
class AgentState(TypedDict):
    messages: Annotated[list[BaseMessage], operator.add]
    reasoning_trace: str
    tool_to_call: str
    tool_input: dict
    final_answer: str

# 2. Define the Reasoning Node (Where the agent decides what to do)
def reasoning_node(state: AgentState):
    """Analyzes the user's question, writes a reasoning trace, and picks a tool."""
    messages = state["messages"]
    latest_query = messages[-1].content.lower()

    # Simple rule-based reasoning simulation (or you can connect an LLM here)
    if "top" in latest_query or "list" in latest_query or "product" in latest_query or "sub-category" in latest_query:
        reasoning_trace = "The user is asking for specific items or a ranked list. I should use the Data Query Tool."
        tool_to_call = "query_sales_data"
        tool_input = {"top_n": 5}
        if "region" in latest_query:
            # simple keyword check for region
            for reg in ['west', 'east', 'central', 'south']:
                if reg in latest_query:
                    tool_input["region"] = reg.capitalize()
    elif "chart" in latest_query or "plot" in latest_query or "visualize" in latest_query:
        reasoning_trace = "The user wants a visual representation or chart of the categories. I should use the Charting Tool."
        tool_to_call = "generate_sales_chart"
        tool_input = {}
    else:
        reasoning_trace = "The user is asking for a general metric like total sales or profit. I should use the Calculation Tool."
        tool_to_call = "calculate_metrics"
        tool_input = {"metric_type": "total_sales"}
        if "profit" in latest_query:
            tool_input["metric_type"] = "total_profit"

    return {
        "reasoning_trace": reasoning_trace,
        "tool_to_call": tool_to_call,
        "tool_input": tool_input
    }

# 3. Define the Tool Execution Node
def tool_node(state: AgentState):
    """Executes the chosen tool function."""
    tool_name = state["tool_to_call"]
    tool_input = state["tool_input"]

    result = None
    if tool_name == "query_sales_data":
        result = query_sales_data(**tool_input)
    elif tool_name == "calculate_metrics":
        result = calculate_metrics(**tool_input)
    elif tool_name == "generate_sales_chart":
        result = generate_sales_chart(**tool_input)

    return {"messages": [AIMessage(content=str(result))]}

# 4. Define the Response Synthesis Node (Turns raw tool output into a nice analyst answer)
def synthesis_node(state: AgentState):
    """Synthesizes the tool output into a plain-language insight."""
    trace = state["reasoning_trace"]
    last_message = state["messages"][-1].content

    synthesized_response = f"**Reasoning / Plan:** {trace}\n\n**Analyst Insight:** Based on the data analysis, here are the findings: {last_message}"

    return {"final_answer": synthesized_response}

print("Agent nodes defined successfully!")

# 1. Initialize the State Graph
workflow = StateGraph(AgentState)

# 2. Add Nodes to the Graph
workflow.add_node("reasoning", reasoning_node)
workflow.add_node("tools", tool_node)
workflow.add_node("synthesis", synthesis_node)

# 3. Define the Flow (Edges)
workflow.set_entry_point("reasoning")

# Route directly from reasoning to tools
workflow.add_edge("reasoning", "tools")

# Route from tools to synthesis
workflow.add_edge("tools", "synthesis")

# End the graph after synthesis
workflow.add_edge("synthesis", END)

# 4. Compile the Graph
app_graph = workflow.compile()

print("LangGraph compiled successfully!")

# Test the compiled graph with a sample question
initial_state = {
    "messages": [HumanMessage(content="What are the top products by sales?")]
}

# Invoke the graph
result = app_graph.invoke(initial_state)

print(result["final_answer"])

