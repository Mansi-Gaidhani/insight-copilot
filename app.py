def query_sales_data(region: str = None, category: str = None, top_n: int = 5):
    """Tool 1: Filters data by region and/or category and returns top items by sales."""
    filtered_df = df.copy()

    if region:
        filtered_df = filtered_df[filtered_df['Region'].str.lower() == region.lower()]
