import gradio as gr
import pandas as pd
from langchain_core.messages import HumanMessage

# Define the prediction function that feeds questions directly into your LangGraph app
def run_insight_copilot(user_query):
    if not user_query.strip():
        return "Please enter a valid question."

    # Run through the compiled LangGraph workflow
    state = {"messages": [HumanMessage(content=user_query)]}
    result = app_graph.invoke(state)
    return result["final_answer"]

# Launch the Gradio Interface
demo = gr.Interface(
    fn=run_insight_copilot,
    inputs=gr.Textbox(
        lines=2,
        placeholder="e.g., What are the top products by sales?",
        label="Ask Insight Copilot"
    ),
    outputs=gr.Markdown(label="Agent Response"),
    title="📊 Global Superstore Insight Copilot",
    description="Powered by LangGraph & Pandas"
)

demo.launch(share=True, inline=False)
